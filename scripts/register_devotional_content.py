def _pair(arabic: str, persian: str) -> str:
    return f"<b>{_esc(arabic)}</b>\n{_esc(persian)}"


def build_ziyarat_ashura_text() -> str:
    blocks: list[str] = []
    for i in range(0, len(ZIYARAT_ASHURA_COUPLETS), CHUNK_SIZE):
        group = ZIYARAT_ASHURA_COUPLETS[i : i + CHUNK_SIZE]
        blocks.append("\n\n".join(_pair(a, p) for a, p in group))

    blocks.append(
        "🔁 <b>صد مرتبه بگویید:</b>\n\n" + _pair(*HUNDRED_TIMES_1)
    )
    blocks.append(
        "🔁 <b>صد مرتبه بگویید:</b>\n\n" + _pair(*HUNDRED_TIMES_2)
    )
    blocks.append(
        "🔁 <b>صد مرتبه بگویید:</b>\n\n"
        + "\n\n".join(_pair(a, p) for a, p in HUNDRED_TIMES_3)
    )
    blocks.append(
        "🤲 <b>سپس بگویید:</b>\n\n" + "\n\n".join(_pair(a, p) for a, p in CLOSING_LAAN)
    )
    blocks.append(
        "🕌 <b>سپس به سجده بروید و بگویید:</b>\n\n"
        + "\n\n".join(_pair(a, p) for a, p in SAJDA)
    )
    return "\x1e".join(blocks)


